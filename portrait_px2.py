def pal(hair, suit, shirt, tie, gold, extra=None):
    p = {'O': OUTLINE, **SKIN, **EYE, **MOUTH, **SHOE}
    if hair: p.update(H=hair[0], h=hair[1], i=hair[2], j=hair[3])
    if suit: p.update(N=suit[0], n=suit[1], l=suit[2], k=suit[3])
    if shirt: p.update(S=shirt[0], s=shirt[1])
    if tie: p.update(T=tie[0], t=tie[1], r=tie[2])
    if gold: p.update(G=gold[0], g=gold[1])
    if extra: p.update(extra)
    return p

